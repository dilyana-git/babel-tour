// The backdrop card (layer 0 of every slab stack) is a HOLE FILLER, and the
// fill it does at runtime is described in DioramaScene.jsx's "backdrop's
// dis-occlusion fill" block as "the real-time half of the inpaint an offline
// pass would do properly". This is the offline half.
//
// source-assets/staircases/backdrop_inpaint.py removes everything past FILL.lo
// from the picture and paints the surround in over it, so layer 0 can be a
// plate that genuinely does not contain the lamp it is filling the hole
// behind. Two things the runtime dilation cannot do, which is the whole reason
// to bother: its outer tap ring reaches 10.5% of plate height and finds no
// background behind anything wider, and it only engages between FILL.lo and
// FILL.hi — so the NEAREST features, the ones with the most parallax travel
// and the worst ghosts, were never painted out at all.
//
// Keyed by the color plate's URL. A plate without an entry keeps the runtime
// dilation exactly as before, so this is opt-in per artwork.
//
// Written at QUARTER SIZE on purpose: the backdrop is never sampled above
// ~mip 3.5 (see blurBias) and is then sunk 0.35 toward the fog, so a
// full-resolution copy would be 19.7 MB of VRAM per plate to feed a surface
// that throws away all of it. Measured against a full-res plate at matching
// mip level: mean difference 0.9/255.
//
