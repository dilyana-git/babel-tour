// Every file a gallery needs before it can be hung, backdrop included.
//
// Tour's restock warms the loader cache "under the same key useTexture will ask
// for, so the re-render finds the plates already decoded and never suspends" —
// and Painting asks for FOUR urls where a plate has a backdrop. Preloading only
// the painting's two would leave the other two to suspend mid-tour, which is
// the one thing that path exists to prevent. So the list is derived here, and
// every caller reads it rather than restating it.
export const platesOf = (scene) => {
  const b = BACKDROP_PLATES[scene.color];
  return b ? [scene.color, scene.depth, b.color, b.depth]
           : [scene.color, scene.depth];
};
